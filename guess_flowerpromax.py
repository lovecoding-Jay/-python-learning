# -*- coding: utf-8 -*-
"""
================================================================================
手写高斯朴素贝叶斯分类器 · 详细注释版
================================================================================

这个程序要解决的问题：
    给一朵鸢尾花的 4 个测量值（花萼长、花萼宽、花瓣长、花瓣宽），
    判断它属于 3 个品种中的哪一个。


================================================================================
"""

# 作用：让我们可以在类型标注里写还没定义的类名（比如 -> "ManualGaussianNB"），
from __future__ import annotations

# pathlib 是 Python 处理文件路径的标准库。
# 相比直接拼字符串 "D:\\xx\\yy"，Path 能自动处理不同系统的斜杠，更安全。
from pathlib import Path

# numpy 是 Python 做数组/矩阵计算的核心库。
# 本例里所有数据都是"一堆数字"，用 numpy 数组存和算最方便。
# 习惯上大家都把它简写成 np。
import numpy as np

# load_iris：把 sklearn 自带的鸢尾花数据集取回来。
from sklearn.datasets import load_iris

# train_test_split：把数据按比例切成训练集和测试集。
# StratifiedKFold：分层 K 折，把数据切成 K 份，保证每份里各品类比例一致。
from sklearn.model_selection import StratifiedKFold, train_test_split

# ------------------------------------------------------------------------------
# 全局常量
# ------------------------------------------------------------------------------

# 都指定一个固定的种子，这样每次运行得到的结果一模一样，方便复现和对比。

RANDOM_STATE = 42


# ==============================================================================
# 第一部分：高斯朴素贝叶斯分类器（核心，全部手写）
# ==============================================================================
class ManualGaussianNB:
    # --------------------------------------------------------------------------
    # 方法 1：fit —— 训练（也可以叫"喂数据、学参数"）
    # --------------------------------------------------------------------------
    def fit(self, X, y):
        """
        参数：
            X：特征表，形状 (样本数, 特征数)，本例是 (105, 4)。
            y：答案，形状 (样本数,)，本例是 0/1/2 代表三个品种。

        这一步"学习"其实只是数数：数出每类有多少个、每类每个特征的均值方差。
        它不做任何迭代优化，所以朴素贝叶斯的训练非常快。
        """
        # np.unique(y)：把 y 里重复的值去掉、并排序，得到所有类别。
        # 本例 y 里只有 0、1、2，所以 classes_ = [0, 1, 2]。
        # 变量名后面加下划线（classes_）是 sklearn 的约定：表示"训练之后才有的属性"。
        self.classes_ = np.unique(y)

        # 准备三个字典，键是类别，值是那一类的统计量。
        #   先验 prior_ ：某类占的比例，一个数
        #   均值 mean_  ：某类在该特征上的平均值，4 个数（每个特征一个）
        #   方差 var_   ：某类在该特征上的波动大小，4 个数
        self.prior_, self.mean_, self.var_ = {}, {}, {}

        # 对每个类别分别统计一遍
        for cls in self.classes_:
            # X[y == cls] 是 numpy 的"布尔索引"：
            # y == cls 得到一串 True/False，拿它去挑 X 的行，
            # 就得到"所有属于该类的样本"。
            X_cls = X[y == cls]

            # 类别是 numpy 类型，转成普通 int，方便当字典的键
            c = int(cls)

            # 先验 P(c) = 该类的样本数 ÷ 总样本数。
            # 本例三类各 35 个、共 105 个，所以每个先验都是 35/105 ≈ 0.3333。
            self.prior_[c] = len(X_cls) / len(X)

            # 均值 μ：axis=0 表示"沿着行方向、对每一列求平均"，
            # 也就是对 4 个特征各自算平均，返回 4 个数。
            self.mean_[c] = X_cls.mean(axis=0)

            # 方差 σ²：同样对每个特征算方差，返回 4 个数。

            # 万一某类某特征在训练集里所有取值都一样，方差就是 0，
            # 之后算高斯密度公式里有"除以方差"，0 会直接让程序报错。
            # 加上一个极小的数，既不影响结果，又避免除零。
            self.var_[c] = X_cls.var(axis=0) + 1e-9

        # 返回 self 是约定俗成的写法，这样可以链式调用：
        # model = ManualGaussianNB().fit(X, y)
        return self

    # --------------------------------------------------------------------------
    # 方法 2：_log_likelihood —— 算"对数似然"
    # --------------------------------------------------------------------------
    def _log_likelihood(self, X, c):
        """
        算 log P(x | 类别 c)，也就是：假设是第 c 类，这组特征出现的概率的【对数】。

        方法名前面加下划线（_log_likelihood）是 Python 的约定：
        表示"这是内部辅助方法，外部别直接调用"。

        【高斯（正态）分布的概率密度公式】
                       1                        (x - μ)²
        N(x; μ, σ²) = ─────────── × exp( -  ─────────── )
                     √(2πσ²)                  2σ²


                                  1
        log N = -0.5 × [ log(2πσ²) + ── × (x - μ)² ]
                                  σ²
        代码里写的就是这一行。
        """
        mu = self.mean_[c]    # 这一类的均值（4 个数）
        var = self.var_[c]    # 这一类的方差（4 个数）

        # numpy 的"广播"：X 是 (样本数, 4)，mu 是 (4,)，
        # (X - mu) 会自动把 mu 复制到每一行去减，得到同样形状的数组。
        #
        #   np.log(2.0 * np.pi * var)     —— 公式里的 log(2πσ²)
        #   ((X - mu) ** 2) / var         —— 公式里的 (x-μ)²/σ²
        #   两者相加、乘 -0.5                —— 就是上面那行公式
        #
        # axis=1 表示"把 4 个特征的结果加起来"，
        # 这就是"朴素"假设在代码里的具体体现：4 个特征的对数概率直接相加
        # （因为 log(ab) = log a + log b，相乘等价于对数相加）。
        #
        # 返回：(样本数,) 的一维数组，每个样本一个对数似然值。
        return -0.5 * np.sum(
            np.log(2.0 * np.pi * var) + ((X - mu) ** 2) / var, axis=1
        )

    # --------------------------------------------------------------------------
    # 方法 3：predict —— 预测
    # --------------------------------------------------------------------------
    def predict(self, X):
        """
        对每个样本，算出它在三个类别上的"分数"，取最高的那个当预测结果。

        分数 = log 先验 + log 似然
             = log P(c) + log P(x | c)

        注意这里是【对数】！原因见下面 print 部分的说明：
        概率都是小于 1 的正数，连乘会越来越小，小到计算机存不下就变成 0；
        取对数之后"连乘变连加"，数值就稳定了。
        而且 log 是单调递增的，比大小不会受影响——原来谁大，取对数后还是谁大。
        """
        # 列表推导式：对三个类别各算一列分数。
        # np.column_stack 把这些一维数组竖着拼起来，
        # 得到形状 (样本数, 类别数) 的二维数组 scores。
        # 例如 scores[0] 就是"第 1 个样本在 3 个类别上各自的分数"。
        scores = np.column_stack(
            [
                np.log(self.prior_[int(c)]) + self._log_likelihood(X, int(c))
                for c in self.classes_
            ]
        )

        # np.argmax(scores, axis=1)：对每一行找"最大值在哪一列"，
        # 返回列的下标（0/1/2）。
        # 再拿这个下标去 self.classes_ 里查真正的类别标签，作为最终预测。
        return self.classes_[np.argmax(scores, axis=1)]


# ==============================================================================
# 第二部分：一个自己写的准确率函数
# ==============================================================================
def accuracy(y_true, y_pred):
    """
    准确率 = 预测对的个数 ÷ 总个数。

    (np.asarray(y_true) == np.asarray(y_pred)) 会逐个位置比较，
    得到一个 True/False 数组；
    np.mean() 对这个数组求平均——True 当 1、False 当 0，
    所以平均值就直接等于"正确率"。
    """
    return float(np.mean(np.asarray(y_true) == np.asarray(y_pred)))


# ==============================================================================
# 第三部分：主流程
# ==============================================================================
def main():
    # --------------------------------------------------------------------------
    # 步骤 1：加载数据
    # --------------------------------------------------------------------------
    iris = load_iris()          # 取回鸢尾花数据集（一个"大字典"一样的对象）
    X, y = iris.data, iris.target
    # X：150 行 × 4 列，每行是一朵花的 4 个测量值
    # y：150 个数，取值 0/1/2，代表三个品种

    # --------------------------------------------------------------------------
    # 步骤 2：划分训练集 / 测试集
    # --------------------------------------------------------------------------

    # test_size=0.3      ：30% 当测试集 → 150 × 0.3 = 45 个，剩 105 个训练
    # random_state=42    ：固定随机种子，保证每次划分结果一样，实验可复现
    # stratify=y         ：分层抽样。让训练 / 测试集里三个品种的比例
    #                      和原始数据一致（3 类各占 1/3），不会某类全被抽走
    #
    # 返回的 4 个值顺序固定是：训练特征、测试特征、训练答案、测试答案
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.3, random_state=RANDOM_STATE, stratify=y
    )

    # --------------------------------------------------------------------------
    # 步骤 3：用训练集"训练"（这里就是数出各种统计量）
    # --------------------------------------------------------------------------
    model = ManualGaussianNB().fit(X_train, y_train)

    # --------------------------------------------------------------------------
    # 步骤 4：在测试集上预测并算准确率
    # --------------------------------------------------------------------------
    pred = model.predict(X_test)             # 逐个预测 45 个测试样本
    test_acc = accuracy(y_test, pred)        # 和标准答案对比

    # --------------------------------------------------------------------------
    # 步骤 5：5 折交叉验证（手写，没有用 sklearn 的 cross_val_score）
    # --------------------------------------------------------------------------

    # 这里只在 X_train / y_train 上做，绝不碰测试集！
    # 测试集要留到最后"一次性"检验，否则就数据泄漏。
    #
    # StratifiedKFold：分折时也保持类别比例一致。
    # shuffle=True    ：先打乱顺序再分，避免原数据"前 50 个都是同一类"造成偏差。
    skf = StratifiedKFold(n_splits=5, shuffle=True, random_state=RANDOM_STATE)

    fold_accs = []                           # 存每一折的准确率
    for tr_idx, va_idx in skf.split(X_train, y_train):
        # 每一折给出两组下标：
        #   tr_idx：这一折用来"训练"的样本编号
        #   va_idx：这一折用来"考试"的样本编号
        m = ManualGaussianNB().fit(X_train[tr_idx], y_train[tr_idx])
        # 用这折的训练子集重新训练一个模型，再在验证子集上打分。
        # 注意要新建模型（m），不能复用上面那个 model，否则会互相污染。
        fold_accs.append(accuracy(y_train[va_idx], m.predict(X_train[va_idx])))

    # --------------------------------------------------------------------------
    # 步骤 6：打印结果
    # --------------------------------------------------------------------------
    # f"..." 是 f-string（格式化字符串），大括号里的变量会被替换成它的值。
    # :.4f 表示"保留 4 位小数"。
    print("数据集：sklearn iris（150 个样本，4 个特征，3 个类别）")
    print(f"划分：训练集 {len(X_train)} 个，测试集 {len(X_test)} 个（分层抽样）")
    print(f"每类先验 P(c)：{[round(model.prior_[c], 4) for c in model.classes_]}")
    print()
    print(f"手写高斯朴素贝叶斯 测试集准确率：{test_acc:.4f}"
          f"（{int(round(test_acc * len(y_test)))}/{len(y_test)}）")
    print(f"5 折交叉验证：{[round(a, 4) for a in fold_accs]}")
    print(f"5 折交叉验证平均：{np.mean(fold_accs):.4f}")

    # --------------------------------------------------------------------------
    # 步骤 7：画图
    # --------------------------------------------------------------------------

    try:
        import matplotlib
        # "Agg" 是"无界面"的绘图后端：只在后台画图并存成文件，不弹窗口。
        # 做作品集需要的是"图文件"，不是一闪而过的窗口，所以用 Agg。
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("\n（本机没装 matplotlib，跳过画图。想生成图请先 pip install matplotlib）")
        return          # 直接结束 main()，后面的画图代码不执行

    # __file__ 是当前这个 .py 文件的路径，
    # .resolve() 拿到绝对路径，.parent 是它所在的文件夹，
    # 再拼上 "results"，就是结果图的存放目录。
    # 用"文件所在位置"来定位，好处是不管你从哪个目录运行脚本，路径都不会错。
    result_dir = Path(__file__).resolve().parent / "results"
    result_dir.mkdir(exist_ok=True)          # 目录不存在就创建；已存在也不报错

    # 横轴标签：5 折 + 测试集，一共 6 根柱子
    labels = [f"Fold {i+1}" for i in range(len(fold_accs))] + ["Test"]
    scores = fold_accs + [test_acc]          # 对应的 6 个分数

    plt.figure(figsize=(7, 4))               # 新建一张 7×4 英寸的画布
    # 画柱状图：前 5 根浅蓝（每一折），最后一根深蓝（测试集）
    bars = plt.bar(labels, scores, color=["#93c5fd"] * len(fold_accs) + ["#3b82f6"])
    plt.ylim(0, 1.0)                         # 纵轴固定 0~1，方便横向比较
    plt.ylabel("Accuracy")                   # 纵轴标题（用英文，避免中文字体缺失问题）
    plt.title("Manual GaussianNB on iris: 5-fold CV vs Test")

    # 在每根柱子顶上写分数，例如 0.952
    for bar, s in zip(bars, scores):
        # get_x() 是柱子左边缘；加上半个宽度就得到柱子中心，文字才能居中
        plt.text(bar.get_x() + bar.get_width() / 2, s + 0.02, f"{s:.3f}", ha="center")

    plt.tight_layout()                       # 自动微调边距，避免文字被裁掉
    out = result_dir / "nb_iris_cv.png"      # 输出文件路径
    plt.savefig(out, dpi=160)                # 保存图片，dpi=160 表示清晰度
    plt.close()                              # 关掉画布，释放内存
    print(f"图已保存：{out}")



if __name__ == "__main__":
    main()
